def at(key: str, **kwargs) -> str:
    """Текст адмінки поточною мовою. Невідомий ключ → KeyError, невідома мова → uk."""
    lang = admin_lang()
    table = _A.get(lang) or _A[DEFAULT_ADMIN_LANG]
    template = table.get(key) or _A[DEFAULT_ADMIN_LANG].get(key)
    if template is None:
        raise KeyError(f"admin i18n: missing key {key!r}")
    return template.format(**kwargs) if kwargs else template


def event_label(code: str) -> str:
    """Код події сповіщення (decrease, target_reached, ...) → підпис мовою адмінки.
    queries.NOTIF_EVENT_LABELS лишається українським — сторінки беруть підпис звідси. Невідомий код → сам код."""
    try:
        return at(f"event_{code}")
    except KeyError:
        return code


def slot_labels(mapping: dict[str, str]) -> str:
    """{код: ключ} → JS-об'єкт {код: переклад} для Vue-шаблонів слотів таблиць.

        tbl.add_slot("body-cell-status", f"...{{{{ {slot_labels({'active': 'status_active'})}[props.value] }}}}...")
    """
    return json.dumps({code: at(key) for code, key in mapping.items()}, ensure_ascii=False)


