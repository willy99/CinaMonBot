ThemeMode = Literal["dark", "light"]
DEFAULT_THEME: ThemeMode = "dark"
THEME_KEY = "admin_theme"
THEME_MODES: tuple[ThemeMode, ...] = ("dark", "light")


# ─── Сесія ───────────────────────────────────────────────────────

def _storage_get(key: str, default: str) -> str:
    """app.storage.user доступний лише всередині сторінки; інакше — значення за замовчуванням."""
    try:
        value = app.storage.user.get(key)
    except Exception:  # noqa: BLE001 — немає клієнта / storage_secret
        return default
    return value if isinstance(value, str) else default


def admin_lang() -> str:
    lang = _storage_get(LANG_KEY, DEFAULT_ADMIN_LANG)
    return lang if lang in ADMIN_LANGUAGES else DEFAULT_ADMIN_LANG


def set_admin_lang(code: str) -> None:
    if code not in ADMIN_LANGUAGES:
        raise ValueError(f"admin i18n: unknown language {code!r}")
    app.storage.user[LANG_KEY] = code


def theme_mode() -> ThemeMode:
    mode = _storage_get(THEME_KEY, DEFAULT_THEME)
    return mode if mode in THEME_MODES else DEFAULT_THEME  # type: ignore[return-value]


def set_theme_mode(mode: str) -> None:
    if mode not in THEME_MODES:
        raise ValueError(f"admin theme: unknown mode {mode!r}")
    app.storage.user[THEME_KEY] = mode


