def amoney(amount, currency: str | None) -> str:
    """Сума з валютою мовою адмінки: 1 234 грн (uk) / ₴1,234 (en). None → '—'."""
    if amount is None:
        return "—"
    return fmt_money(Decimal(str(amount)), currency, admin_lang())


def anum(n) -> str:
    """Ціле з розділювачем тисяч: '1 234' (uk) / '1,234' (en). Рядки повертаються як є."""
    if isinstance(n, str):
        return n
    try:
        return fmt_number(int(n), admin_lang())
    except (TypeError, ValueError):
        return str(n)


_EN_MONTHS = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")


def adate(dt: datetime | None, with_time: bool = False) -> str:
    """Дата мовою адмінки: '11.10.2026' (uk) / '11 Oct 2026' (en); with_time додає ' 15:30'."""
    if dt is None:
        return "—"
    from app.timeutil import to_kyiv
    dt = to_kyiv(dt)  # у базі UTC → показуємо за Києвом
    lang = admin_lang()
    day = dt.strftime("%d.%m.%Y") if lang == "uk" else f"{dt.day} {_EN_MONTHS[dt.month - 1]} {dt.year}"
    return f"{day} {dt:%H:%M}" if with_time else day
